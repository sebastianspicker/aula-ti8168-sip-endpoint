"""Confine private firmware CLI output; pure fixture builders remain independent.

Only command-line entry points call this helper. Source inputs may live outside
this checkout, but private generated bytes and receipts belong below its .work.
The checkout and its ancestors are assumed to remain under the user's control.
"""
from __future__ import annotations

import os
import stat
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]


def _destination(requested: Path, repository: Path) -> tuple[Path, Path]:
    root = repository.resolve(strict=True)
    if ".." in requested.parts:
        raise ValueError("private output must not contain '..'")
    lexical = requested.absolute()
    # Reject aliases before resolving: a symlink into .work is still unsafe.
    current = Path(lexical.anchor)
    for part in lexical.parts[1:]:
        current /= part
        try:
            mode = current.lstat().st_mode
        except FileNotFoundError:
            break
        if stat.S_ISLNK(mode):
            raise ValueError("private output ancestors must not be symlinks")
    # samefile accepts the filesystem's own case equivalence (Git versus git)
    # without accepting a different checkout or assuming case-insensitivity.
    for ancestor in lexical.parents:
        try:
            matches = ancestor.samefile(root)
        except FileNotFoundError:
            continue
        if matches:
            relative = lexical.relative_to(ancestor)
            break
    else:
        raise ValueError("private output must remain below this checkout's .work")
    if relative.parts[0] != ".work" or len(relative.parts) < 2:
        raise ValueError("private output must be strictly below this checkout's .work")
    return root, relative


def prepare_output(requested: Path, *, repository: Path = ROOT,
                   container: bool = False) -> Path:
    """Validate before reading inputs; create only private output ancestors.

    Fresh archive/composition leaves remain absent for the builder's exclusive
    mkdir. A runner container may already exist: its individual runs use fresh
    mkdtemp children and never overwrite previous evidence.
    """
    root, relative = _destination(requested, repository)
    flags = os.O_RDONLY | os.O_DIRECTORY | getattr(os, "O_NOFOLLOW", 0)
    descriptor = os.open(root, flags)
    try:
        parts = relative.parts if container else relative.parts[:-1]
        for index, part in enumerate(parts):
            try:
                os.mkdir(part, mode=0o700, dir_fd=descriptor)
            except FileExistsError:
                pass
            child = os.open(part, flags, dir_fd=descriptor)
            try:
                info = os.fstat(child)
                mode = stat.S_IMODE(info.st_mode)
                if (not stat.S_ISDIR(info.st_mode) or info.st_uid != os.getuid()
                        or (mode & 0o022 if index == 0 else mode != 0o700)):
                    raise ValueError("private output parents must be owned private directories (0700 below .work)")
            except BaseException:
                os.close(child)
                raise
            os.close(descriptor)
            descriptor = child
        if not container:
            try:
                os.stat(relative.name, dir_fd=descriptor, follow_symlinks=False)
            except FileNotFoundError:
                pass
            else:
                raise ValueError("private output already exists; choose a fresh directory")
    finally:
        os.close(descriptor)
    return root / relative
